#!/usr/bin/env python3
"""rco_attr_gen.py -- the RCO object / animation attribute layouts, as C, for the menu engine
(main/support/umd/menu/, docs/p9.md S3.3).

The layouts are RCOMage's data files (github.com/kakaroto/RCOMage, LGPL 2.1:
data/objattribdef-psp.ini, data/animattribdef-psp.ini): per object / animation type, its extra
words in order, each `int` / `float` / `unk` (one 32-bit word) or a reference (`event`, `ref`, `image`,
`text`, `model`, `font`, `object`, `anim`: two words, {type, pointer}). They are DATA describing
the format, read here and written as tables; the engine's code is its own.

    rco_attr_gen.py [--check]     -> main/support/umd/menu/rco_attrs.h

Types are numbered in file order from 0 (ObjectTree / AnimTree): the RCO entry's type byte. A
type with no attributes listed has none (the engine still reads its entry header and children).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
REFS = os.environ.get("UMD_REFS_DIR", os.path.join(ROOT, "..", "..", "umd_repos"))
DATA = os.path.join(REFS, "RCOMage", "data")
OUT = os.path.join(ROOT, "main", "support", "umd", "menu", "rco_attrs.h")

KIND = {"unk": "RCO_A_UNK", "int": "RCO_A_INT", "float": "RCO_A_FLOAT", "event": "RCO_A_EVENT", "ref": "RCO_A_REF",
        "image": "RCO_A_IMAGE", "text": "RCO_A_TEXT", "model": "RCO_A_MODEL", "font": "RCO_A_FONT",
        "object": "RCO_A_OBJECT", "anim": "RCO_A_ANIM"}


def parse(path):
    types = []                                # [(name, [(attr, kind)])]
    for ln in open(path, encoding="latin-1"):
        ln = ln.split(";")[0].strip()
        if not ln:
            continue
        if ln.startswith("["):
            types.append((ln.strip("[]"), []))
        elif "=" in ln and types:
            a, k = (x.strip() for x in ln.split("=", 1))
            if k not in KIND:
                raise SystemExit("rco_attr_gen: %s: unknown kind %r" % (path, k))
            types[-1][1].append((a, k))
    return types


def emit(prefix, types):
    out = []
    for i, (name, attrs) in enumerate(types):
        out.append("static const rco_attr_def %s_%s[] = {" % (prefix, name.lower()))
        for a, k in attrs:
            out.append('    { "%s", %s },' % (a, KIND[k]))
        out.append("    { 0, RCO_A_END }")
        out.append("};")
    out.append("static const rco_type_def %s_TYPES[%d] = {" % (prefix.upper(), len(types)))
    for name, attrs in types:
        words = sum(1 if k in ("int", "float", "unk") else 2 for _, k in attrs)
        out.append('    { "%s", %s_%s, %d, %d },' % (name, prefix, name.lower(), len(attrs), words))
    out.append("};")
    out.append("#define %s_NTYPES %d" % (prefix.upper(), len(types)))
    return out


def text():
    obj = parse(os.path.join(DATA, "objattribdef-psp.ini"))
    anim = parse(os.path.join(DATA, "animattribdef-psp.ini"))
    out = ["// rco_attrs.h -- GENERATED by tools/rco_attr_gen.py from RCOMage's attribute definitions",
           "// (data/objattribdef-psp.ini, data/animattribdef-psp.ini; LGPL 2.1): do not edit.",
           "#pragma once",
           "",
           "typedef enum { RCO_A_END, RCO_A_UNK, RCO_A_INT, RCO_A_FLOAT, RCO_A_EVENT, RCO_A_REF, RCO_A_IMAGE, RCO_A_TEXT,",
           "               RCO_A_MODEL, RCO_A_FONT, RCO_A_OBJECT, RCO_A_ANIM } rco_attr_kind;",
           "typedef struct { const char *name; rco_attr_kind kind; } rco_attr_def;",
           "typedef struct { const char *name; const rco_attr_def *attrs; int nattrs; int words; } rco_type_def;",
           ""]
    out += emit("rco_obj", obj) + [""] + emit("rco_anim", anim)
    return "\n".join(out) + "\n"


def main():
    t = text()
    cur = open(OUT).read() if os.path.exists(OUT) else None
    if "--check" in sys.argv[1:]:
        if cur != t:
            print("rco_attr_gen: %s differs (run tools/rco_attr_gen.py)" % os.path.relpath(OUT, ROOT))
            return 1
        print("rco_attr_gen: OK")
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    if cur != t:
        open(OUT, "w").write(t)
        print("rco_attr_gen: wrote %s" % os.path.relpath(OUT, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
